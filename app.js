function translateTextValue(value) {
  if (!value) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  const core = value.trim();
  if (!core) return value;

  let translated = VI_TRANSLATIONS[core];

  // Some HTML sentences are split by nested tags such as <strong>.
  // Translate all recognised fragments, starting with the longest key.
  if (!translated) {
    translated = core;
    const keys = Object.keys(VI_TRANSLATIONS).sort((a, b) => b.length - a.length);
    for (const key of keys) {
      if (key && translated.includes(key)) {
        translated = translated.split(key).join(VI_TRANSLATIONS[key]);
      }
    }
  }

  translated = translated
    .replace(/^LAYER\s+(\d+)$/i, 'LỚP $1')
    .replace(/^(\d+)h ago$/, '$1 giờ trước')
    .replace(/^(\d+)d ago$/, '$1 ngày trước')
    .replace(/^~(\d+) hrs\/week$/, '~$1 giờ/tuần');

  return leading + translated + trailing;
}

function translateElement(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const tag = node.parentElement?.tagName;
      if (!node.nodeValue.trim() || ['SCRIPT','STYLE','NOSCRIPT'].includes(tag)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => {
    if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
    node.nodeValue = currentLanguage === 'vi' ? translateTextValue(originalTextNodes.get(node)) : originalTextNodes.get(node);
  });

  root.querySelectorAll?.('[placeholder],[title],[aria-label],[data-text]').forEach(el => {
    if (!originalAttributes.has(el)) {
      originalAttributes.set(el, {
        placeholder: el.getAttribute('placeholder'), title: el.getAttribute('title'),
        ariaLabel: el.getAttribute('aria-label'), dataText: el.getAttribute('data-text')
      });
    }
    const o = originalAttributes.get(el);
    const set = (attr, val) => {
      if (val == null) return;
      el.setAttribute(attr, currentLanguage === 'vi' ? translateTextValue(val) : val);
    };
    set('placeholder', o.placeholder); set('title', o.title); set('aria-label', o.ariaLabel); set('data-text', o.dataText);
  });
}

